const templates: Template[] = [];

function add(
  id: string,
  topic: string,
  difficulty: "Easy" | "Moderate" | "Difficult",
  rows: FactRow[],
  forward: string,
  reverse: string | undefined,
  explain: string,
  matchLabel?: string,
) {
  templates.push(
    ...factTemplate({
      id,
      subject: "Hindi Grammar",
      topic,
      difficulty,
      exams: HI,
      rows,
      forward,
      reverse,
      explain,
    }),
    matchTemplate({
      id,
      subject: "Hindi Grammar",
      topic,
      difficulty,
      exams: HI,
      rows,
      label: matchLabel,
    }),
    statementTemplate({
      id,
      subject: "Hindi Grammar",
      topic,
      difficulty,
      exams: HI,
      rows,
      label: matchLabel,
    }),
    statementCountTemplate({
      id,
      subject: "Hindi Grammar",
      topic,
      difficulty,
      exams: HI,
      rows,
      label: matchLabel,
    }),
  );
}

